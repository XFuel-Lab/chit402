// scripts/gas-snapshot.cjs
// Runs the core contract tests with gas reporting enabled and writes
// a gas-snapshot.txt baseline. Run this manually when you want to update
// the baseline, then commit the result.
//
// Usage:
//   node scripts/gas-snapshot.cjs              # generate snapshot
//   node scripts/gas-snapshot.cjs --check      # compare against committed baseline
//
// In CI, use: REPORT_GAS=true npm run test:contracts:core:solidity

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const SNAPSHOT_FILE = path.join(__dirname, '..', 'gas-snapshot.txt');
const CHECK_MODE = process.argv.includes('--check');

console.log(`\n=== XFuel Gas Snapshot ${CHECK_MODE ? '(check mode)' : '(generate mode)'} ===\n`);

let output;
try {
  output = execSync('npx hardhat test test/phase3/*.test.cjs test/security/SplitterBranches.test.cjs', {
    env: { ...process.env, REPORT_GAS: 'true', HARDHAT_FAST: 'true' },
    cwd: path.join(__dirname, '..'),
    encoding: 'utf8',
    stdio: ['pipe', 'pipe', 'pipe'],
  });
} catch (err) {
  console.error('Test run failed:', err.message);
  process.exit(1);
}

// Extract gas table lines (hardhat-gas-reporter format)
const gasLines = output
  .split('\n')
  .filter(l => l.includes('·') && (l.includes('gas') || l.includes('Deployment') || /\d{4,}/.test(l)))
  .join('\n');

const timestamp = new Date().toISOString().split('T')[0];
const snapshot = `# XFuel Gas Snapshot — ${timestamp}\n# Generated by: node scripts/gas-snapshot.cjs\n\n${gasLines}\n`;

if (CHECK_MODE) {
  if (!fs.existsSync(SNAPSHOT_FILE)) {
    console.log('No baseline snapshot found. Run without --check to generate one.');
    process.exit(0);
  }
  const baseline = fs.readFileSync(SNAPSHOT_FILE, 'utf8');
  const baselineLines = new Map(
    baseline.split('\n')
      .filter(l => l.includes('·'))
      .map(l => {
        const parts = l.split('·').map(p => p.trim());
        return [parts[0], l];
      })
  );
  const currentLines = new Map(
    gasLines.split('\n')
      .filter(l => l.includes('·'))
      .map(l => {
        const parts = l.split('·').map(p => p.trim());
        return [parts[0], l];
      })
  );

  let regressions = 0;
  for (const [key, currentLine] of currentLines) {
    const baselineLine = baselineLines.get(key);
    if (!baselineLine) continue;
    const currentGas = parseInt((currentLine.match(/(\d{4,})/) || [])[1] || '0');
    const baselineGas = parseInt((baselineLine.match(/(\d{4,})/) || [])[1] || '0');
    if (currentGas > baselineGas * 1.05) {  // >5% regression = fail
      console.log(`❌ Gas regression: ${key}`);
      console.log(`   Baseline: ${baselineGas.toLocaleString()}`);
      console.log(`   Current:  ${currentGas.toLocaleString()} (+${Math.round((currentGas / baselineGas - 1) * 100)}%)`);
      regressions++;
    }
  }

  if (regressions === 0) {
    console.log('✅ No gas regressions detected.');
  } else {
    console.log(`\n❌ ${regressions} gas regression(s) detected. Update baseline or fix regressions.`);
    process.exit(1);
  }
} else {
  fs.writeFileSync(SNAPSHOT_FILE, snapshot);
  console.log(`✅ Snapshot written to gas-snapshot.txt`);
  console.log('\nGas table:');
  console.log(gasLines || '(no gas data found — check REPORT_GAS=true is working)');
}
